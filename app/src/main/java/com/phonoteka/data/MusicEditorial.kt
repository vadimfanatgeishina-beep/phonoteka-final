/** Local music copy for the lab's paged post feed. IDs and network/cache behaviour stay intact. */
object MusicEditorial {
    private val titles = listOf(
        "Вечерний плейлист", "Альбомы для дороги", "Спокойный электронный звук",
        "Гитарные открытия", "Ритм большого города", "Музыка для концентрации",
        "Новые голоса", "Треки для прогулки", "Акустический вечер",
        "Танцевальная подборка", "Саундтреки и воспоминания", "Джаз после полуночи",
        "Инди на повторе", "Музыка для путешествия", "Бас и настроение",
        "Тихие песни", "Рок без спешки", "Летний микс",
        "Мелодии для работы", "Звуки выходного"
    )
    private val descriptions = listOf(
        "Собери очередь из любимых треков и отметь композиции, к которым хочется вернуться.",
        "Сравни звучание альбомов и сохрани песни, которые подходят под настроение.",
        "Открой новые сочетания синтезаторов, ритма и мягкого вокала.",
        "Добавь гитарные композиции в библиотеку и оставь заметку о любимом моменте.",
        "Начни с энергичного трека, затем плавно смени темп плейлиста."
    )
    private val comments = listOf(
        "Хорошее начало для вечернего плейлиста. Хочется ещё пару спокойных треков в конце.",
        "Слушал в дороге — переход от мягкого звучания к более быстрому темпу получился удачным.",
        "Сохранил подборку. Особенно понравилась идея сравнивать альбомы по настроению.",
        "К этому звучанию я бы добавил ещё немного живых инструментов.",
        "Вернулся к списку спустя неделю и нашёл трек, который сначала пропустил.",
        "Для работы такой темп подходит: музыка не отвлекает от текста.",
        "В наушниках детали заметнее. Хочется переслушать альбом целиком.",
        "Сделал заметку к любимой композиции, чтобы потом найти её в библиотеке."
    )

    fun post(source: CatalogPost): CatalogPost = source.copy(
        title = "${titles[(source.id - 1).mod(titles.size)]} · выпуск ${source.id}",
        body = descriptions[(source.id - 1).mod(descriptions.size)]
    )

    fun comment(source: CatalogComment): CatalogComment = source.copy(
        name = "Слушатель ${source.id}", email = "",
        body = comments[(source.id - 1).mod(comments.size)]
    )
}
